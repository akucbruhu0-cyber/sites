// ---------- 8. HELPERS ----------
function stripNiqqud(str) {
  return (str || '')
    .normalize('NFKD')
    .replace(/[\u0591-\u05C7]/g, '')
    .replace(/[-–—־]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeExact(str, ignoreShinSinDot = false) {
  let s = (str || '')
    .normalize('NFKD')
    // איחוד קמץ קטן עם קמץ רגיל וחולם חסר לוי"ו עם חולם רגיל
    .replace(/\u05C7/g, '\u05B8')
    .replace(/\u05BA/g, '\u05B9')
    // הסרת טעמי מקרא, מתג ורפה (שאינם חלק מניקוד החובה)
    .replace(/[\u0591-\u05AF\u05BD\u05BF]/g, '');

  if (ignoreShinSinDot) {
    s = s.replace(/[\u05C1\u05C2]/g, '');
  }

  // מיון קנוני וניקוי כפילויות של סימני הניקוד/הדגש על כל אות (כך שסדר ההקלדה דגש+קמץ או קמץ+דגש זהה תמיד)
  s = s.replace(/([\u05D0-\u05EA])([\u05B0-\u05C7]+)/g, (_, base, marks) => {
    const sortedUnique = Array.from(new Set(marks)).sort().join('');
    return base + sortedUnique;
  });

  // איחוד חולם מלא שנכתב לפני וי"ו (בְּנֹוהִי) עם חולם מלא על הוי"ו (בְּנוֹהִי)
  s = s.replace(/([\u05D0-\u05EA])([\u05B0-\u05C7]*)\u05B9([\u05B0-\u05C7]*)ו(?![\u05B0-\u05C7])/g, (_, base, m1, m2) => {
    const restMarks = Array.from(new Set(m1 + m2)).sort().join('');
    return base + restMarks + 'ו\u05B9';
  });

  return s
    .replace(/[-–—־]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function matchesAnswer(userVal, expected, alts = [], strictNiqqud = false) {
  if (!strictNiqqud) {
    const cleanUser = stripNiqqud(userVal);
    if (!cleanUser) return false;
    return [expected, ...(alts || [])].some((c) => cleanUser === stripNiqqud(c));
  }
  const hasShinDot = /[\u05C1\u05C2]/.test((userVal || '').normalize('NFKD'));
  const ignoreShinSin = !hasShinDot;
  const cleanUser = normalizeExact(userVal, ignoreShinSin);
  if (!cleanUser) return false;
  return [expected, ...(alts || [])].some((c) => cleanUser === normalizeExact(c, ignoreShinSin));
}

