function recordPracticeOutcome(qItem, isRight) {
  const mem = getPracticeMemory();
  if (!mem.byCat[qItem.cat]) mem.byCat[qItem.cat] = { correct: 0, total: 0 };
  mem.byCat[qItem.cat].total += 1;

  if (isRight) {
    practiceState.score++;
    mem.byCat[qItem.cat].correct += 1;
    mem.wrongIds = mem.wrongIds.filter((id) => id !== qItem.id);
  } else {
    if (!mem.wrongIds.includes(qItem.id)) mem.wrongIds.push(qItem.id);
  }
  savePracticeMemory(mem);
}

