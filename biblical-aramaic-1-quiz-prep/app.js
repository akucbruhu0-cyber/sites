function gradeQuiz(quiz) {
  const strict = document.getElementById('strictNiqqudToggle').checked;
  let total = 0;
  let correctCount = 0;

  quiz.partA.rows.forEach((row, rIdx) => {
    row.cells.forEach((cell, cIdx) => {
      if (cell.prefilled) return;
      total++;
      const inp = document.querySelector(`.quiz-input[data-part="a"][data-r="${rIdx}"][data-c="${cIdx}"]`);
      const fb = document.getElementById(`fb-a-${rIdx}-${cIdx}`);
      const ok = matchesAnswer(inp.value, cell.answer, cell.alts || [], strict);
      inp.classList.remove('correct', 'wrong');
      inp.classList.add(ok ? 'correct' : 'wrong');
      if (ok) {
        correctCount++;
        fb.className = 'feedback-line ok';
        fb.textContent = `✓ ${cell.answer}`;
      } else {
        fb.className = 'feedback-line err';
        fb.textContent = `נכון: ${cell.answer} (${cell.note})`;
      }
    });
  });

  quiz.partB.forEach((item, bIdx) => {
    total++;
    const inp = document.querySelector(`.quiz-input[data-part="b"][data-b="${bIdx}"]`);
    const fb = document.getElementById(`fb-b-${bIdx}`);
    const ok = matchesAnswer(inp.value, item.answer, item.alt || [], false);
    inp.classList.remove('correct', 'wrong');
    inp.classList.add(ok ? 'correct' : 'wrong');
    if (ok) {
      correctCount++;
      fb.className = 'feedback-line ok';
      fb.textContent = `✓ ${item.note}`;
    } else {
      fb.className = 'feedback-line err';
      fb.textContent = `נכון: ${item.answer} (${item.note})`;
    }
  });

  const score = Math.round((correctCount / total) * 100);
  saveScore(quiz.code, score);
  renderQuizCards();

  const msg = score >= 85 ? 'שליטה מצוינת! מוכנים לבוחן.' :
              score >= 65 ? 'כיוון טוב — עברו על ההערות האדומות ונסו שוב.' :
                            'כדאי לחזור ללשונית "מפת החומר" ולתרגל את הדגמים.';

  document.getElementById('quizResultBanner').innerHTML = `
    <div class="score-banner">
      <div>
        <div class="card-tag">תוצאת בוחן ${quiz.code}</div>
        <h3>${msg}</h3>
        <p class="muted">עניתם נכון על ${correctCount} מתוך ${total} סעיפים.</p>
      </div>
      <div class="score-number">${score}/100</div>
    </div>
  `;
}

