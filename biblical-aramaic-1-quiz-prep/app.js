function getSavedScores() {
  try { return JSON.parse(localStorage.getItem('aramaic_quiz_scores_v2') || '{}'); }
  catch { return {}; }
}

function saveScore(quizCode, score) {
  const scores = getSavedScores();
  scores[quizCode] = Math.max(scores[quizCode] || 0, score);
  localStorage.setItem('aramaic_quiz_scores_v2', JSON.stringify(scores));
}

